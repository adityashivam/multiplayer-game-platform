/**
 * Generate the platform's CSS theme fallbacks from the default theme's JSON,
 * so the default look is defined once (data/themes/kaboom.kaboom-theme.json)
 * and global.scss never repeats its values by hand.
 *
 * Run: npm run platform:theme-defaults (platform:build runs it first).
 * tests/platform-theme-defaults.test.js fails if the committed file drifts.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { BUILT_IN_PLATFORM_THEMES, readPlatformThemeVariables } from "../public/platform/src/platform-ui/services/platformThemes.js";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PLATFORM_THEME_DEFAULTS_PATH = path.join(repositoryRoot, "public/platform/src/platform-ui/styles/_theme-defaults.generated.scss");

/**
 * The generated stylesheet for the default theme.
 * @returns {string}
 */
export function renderPlatformThemeDefaults() {
  const defaultTheme = BUILT_IN_PLATFORM_THEMES[0];
  const declarations = Object.entries(readPlatformThemeVariables(defaultTheme))
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `// Generated by scripts/generate-platform-theme-defaults.mjs from
// data/themes/${defaultTheme.id}.kaboom-theme.json. Do not edit; change the
// theme JSON and run npm run platform:theme-defaults.
:root {
${declarations}
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(PLATFORM_THEME_DEFAULTS_PATH, renderPlatformThemeDefaults());
  console.log(`Wrote ${path.relative(repositoryRoot, PLATFORM_THEME_DEFAULTS_PATH)}`);
}
